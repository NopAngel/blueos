void
fb_draw_rect(uint32_t x_start, uint32_t y_start, uint32_t width, uint32_t height, uint32_t color)
{
    uint32_t *fb = (uint32_t *)global_fb.virt;
    uint32_t fb_width = global_fb.width;

    if (!fb) return;

    for (uint32_t y = 0; y < height; y++) {
        for (uint32_t x = 0; x < width; x++) {
            uint32_t pixel_x = x_start + x;
            uint32_t pixel_y = y_start + y;

            if (pixel_x < fb_width && pixel_y < global_fb.height) {
                fb[pixel_y * fb_width + pixel_x] = color;
            }
        }
    }
}

void
fb_scroll_up(uint32_t pixels, uint32_t bg_color)
{
    uint32_t *fb = (uint32_t *)global_fb.virt;
    uint32_t width = global_fb.width;
    uint32_t height = global_fb.height;

    if (!fb || width == 0 || height == 0) return;

    /* 1. Desplazar las líneas de píxeles hacia arriba en memoria de video */
    uint32_t size_to_copy = width * (height - pixels);
    uint32_t offset_pixels = width * pixels;

    for (uint32_t i = 0; i < size_to_copy; i++) {
        fb[i] = fb[i + offset_pixels];
    }

    /* 2. Limpiar la última banda inferior con el color de fondo */
    for (uint32_t i = size_to_copy; i < width * height; i++) {
        fb[i] = bg_color;
    }
}

void
fb_draw_char(uint32_t x_start, uint32_t y_start, char c, uint32_t color)
{
    extern char basic_font[128][8]; 

    uint32_t *fb = (uint32_t *)global_fb.virt;
    uint32_t width = global_fb.width;

    if (!fb || c > 127) return;

    /* Recorremos las 8 líneas verticales del carácter */
    for (int y = 0; y < 8; y++) {
        uint8_t bit_row = (uint8_t)basic_font[(uint8_t)c][y];
        
        /* RECORRIDO INVERTIDO: Cambiamos (0x80 >> x) por (1 << x) */
        for (int x = 0; x < 8; x++) {
            if (bit_row & (1 << x)) {
                uint32_t pixel_x = x_start + x;
                uint32_t pixel_y = y_start + y;
                
                if (pixel_x < width && pixel_y < global_fb.height) {
                    fb[pixel_y * width + pixel_x] = color;
                }
            }
        }
    }
}

void
fb_puts(uint32_t x, uint32_t y, const char *str, uint32_t color)
{
    while (*str) {
        fb_draw_char(x, y, *str, color);
        x += 8; 
        str++;
    }
}

