/* Definición global de los datos del framebuffer */
blueos_fb_t global_fb = {0};

/**
 * fb_init - Registra e inicializa los parámetros del Framebuffer base
 */
void
fb_init(uintptr_t phys_addr, uint32_t width, uint32_t height, uint32_t bpp)
{
	global_fb.phys = phys_addr;
	global_fb.virt = (uint8_t *)phys_addr;
	global_fb.width = width;
	global_fb.height = height;
	global_fb.bpp = bpp;
	global_fb.pitch = width * (bpp / 8);

	/* Configuración estándar True Color de 32 bits (RGBA) */
	global_fb.red_shift = 16;
	global_fb.red_size = 8;
	global_fb.green_shift = 8;
	global_fb.green_size = 8;
	global_fb.blue_shift = 0;
	global_fb.blue_size = 8;

	printk("[FB0]: Internal graphics layer registered at %p (%dx%d %dbpp)\n",
	       (void *)phys_addr, width, height, bpp);
}

static int
fb_user_illegal(struct vfs_node *node, void *buffer, uint32_t size, uint32_t offset)
{
	(void)node;
	(void)buffer;
	(void)size;
	(void)offset;
	printk("[fb0] warning: direct read/write requested but blocked.\n");
	return -EINVAL;
}

static int
fb_user_ioctl(struct vfs_node *node, uint64_t request, void *arg)
{
	(void)node;

	switch (request) {
	case FBIOGET_FSCREENINFO: {
		struct fb_fix_screeninfo *fix = (struct fb_fix_screeninfo *)arg;
		mm_memset(fix, 0, sizeof(struct fb_fix_screeninfo));
		
		memcpy(fix->id, "BlueOS_FB", 9);
		fix->smem_start = global_fb.phys;
		fix->smem_len = global_fb.height * global_fb.pitch;
		fix->type = FB_TYPE_PACKED_PIXELS;
		fix->visual = FB_VISUAL_TRUECOLOR;
		fix->line_length = global_fb.pitch;
		fix->mmio_start = global_fb.phys;
		fix->mmio_len = global_fb.height * global_fb.pitch;
		return 0;
	}

	case FBIOGET_VSCREENINFO: {
		struct fb_var_screeninfo *var = (struct fb_var_screeninfo *)arg;
		mm_memset(var, 0, sizeof(struct fb_var_screeninfo));

		var->xres = global_fb.width;
		var->yres = global_fb.height;
		var->xres_virtual = global_fb.width;
		var->yres_virtual = global_fb.height;
		var->bits_per_pixel = global_fb.bpp;

		var->red.offset = global_fb.red_shift;
		var->red.length = global_fb.red_size;
		var->red.msb_right = 1;

		var->green.offset = global_fb.green_shift;
		var->green.length = global_fb.green_size;
		var->green.msb_right = 1;

		var->blue.offset = global_fb.blue_shift;
		var->blue.length = global_fb.blue_size;
		var->blue.msb_right = 1;

		var->transp.offset = 24;
		var->transp.length = 8;
		var->transp.msb_right = 1;

		var->width = global_fb.width / 4;
		var->height = global_fb.height / 4;
		return 0;
	}

	case FBIOPUT_VSCREENINFO:
	case FBIOPUTCMAP:
		return 0;

	default:
		return -ENOTTY;
	}
}

static uintptr_t
fb_user_mmap(struct vfs_node *node, uintptr_t addr, size_t length, int prot, int flags, size_t pgoffset)
{
	(void)node;
	(void)addr;
	(void)prot;
	(void)flags;
	(void)pgoffset;

	if (length == 0) {
		length = global_fb.height * global_fb.pitch;
	}

	/* Alineamos el tamaño del mapeo al bloque de páginas (4096 bytes) */
	size_t aligned_size = (length + 4095) & ~4095;
	uint32_t phys_start = (uint32_t)global_fb.phys;
	
	/* Espacio virtual seguro superior de 32 bits para el proceso de usuario */
	uintptr_t virt_user_base = 0x70000000;

	/* Mapeamos todo el espacio de un tirón usando tu API nativa de BlueOS */
	vmm_map((void *)virt_user_base, phys_start, aligned_size, PAGE_PRESENT | PAGE_RW | PAGE_USER);

	return virt_user_base;
}

/**
 * fb_test_pattern - Dibuja un patrón de barras de colores pasteles en la pantalla
 */
void
fb_test_pattern(void)
{
	/* Apuntamos directamente al mapa de memoria virtual del kernel para la VRAM */
	uint32_t *fb = (uint32_t *)global_fb.virt;
	uint32_t width = global_fb.width;
	uint32_t height = global_fb.height;

	if (!fb) return;

	/* Paleta de colores pasteles (Estilo 90s retro) */
	uint32_t colors[] = {
		0xFFB6C1, /* Rosa Pastel */
		0xCEF0FF, /* Celeste Pastel */
		0xE6E6FA, /* Lavanda */
		0xD8BFD8, /* Cardo / Lila */
		0xFFF0F5, /* Lavanda Blush */
		0xEAFFD0  /* Verde Lima Pastel */
	};
	int num_colors = sizeof(colors) / sizeof(colors[0]);
	uint32_t bar_width = width / num_colors;

	for (uint32_t y = 0; y < height; y++) {
		for (uint32_t x = 0; x < width; x++) {
			int color_index = x / bar_width;
			if (color_index >= num_colors) {
				color_index = num_colors - 1;
			}
			/* Formula indexada estándar: Y * Ancho + X */
			fb[y * width + x] = colors[color_index];
		}
	}
	printk("[FB0]: Test pattern successfully drawn onto screen.\n");
}

